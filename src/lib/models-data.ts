export const ALL_AGENCY_MODELS: AgencyModel[] = [...FEMALE_MODELS, ...MALE_MODELS]

export function getModelsByGender(gender: 'women' | 'men'): AgencyModel[] {
  return gender === 'women' ? FEMALE_MODELS : MALE_MODELS
}

export function getModelById(id: string): AgencyModel | undefined {
  return ALL_AGENCY_MODELS.find((m) => m.id === id)
}

export function getRecommendedModelForProduct(gender: 'women' | 'men', category?: string): AgencyModel {
  const pool = getModelsByGender(gender)
  if (!category) return pool[0]
  const matched = pool.find((m) => m.bestSuitedFor.some((c) => category.toLowerCase().includes(c.toLowerCase())))
  return matched || pool[0]
}
